'use strict';
// Registers StreamSnap with the desktop (app-menu entry + icon) so the window and launcher show its icon.
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const dataHome = process.env.XDG_DATA_HOME || path.join(os.homedir(), '.local', 'share');

function write(file, content, mode) {
  try {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { mode });
  } catch { /* read-only home etc.: the app still works without a menu entry */ }
}

/**
 * The menu entry runs a small wrapper script instead of node directly: desktop launchers start with a bare
 * environment (no shell PATH, no terminal), so the wrapper finds node, runs from the project folder and
 * logs to ~/.config/streamsnap/launch.log. The icon is referenced by absolute path so it shows even when
 * the desktop's icon cache hasn't refreshed.
 */
function ensureDesktopEntry() {
  if (process.platform !== 'linux') return;
  const script = path.join(root, 'bin', 'streamsnap.js');
  const log = path.join(os.homedir(), '.config', 'streamsnap', 'launch.log');
  const wrapper = path.join(dataHome, 'streamsnap', 'launch.sh');
  const nodeDir = path.dirname(process.execPath);
  write(wrapper, `#!/bin/sh
# Generated by StreamSnap. Launches the app and records any startup error in ${log}
mkdir -p "$(dirname "${log}")"
PATH="${nodeDir}:$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
export PATH
NODE="${process.execPath}"
[ -x "$NODE" ] || NODE="$(command -v node)"
cd "${root}" || exit 1
if [ -z "$NODE" ]; then
  echo "$(date): node not found" >> "${log}"
  command -v notify-send >/dev/null && notify-send "StreamSnap" "Node.js was not found. See ${log}"
  exit 1
fi
echo "$(date): starting with $NODE" >> "${log}"
exec "$NODE" "${script}" "$@" >> "${log}" 2>&1
`, 0o755);
  try { fs.chmodSync(wrapper, 0o755); } catch { /* ignore */ }

  const icon = path.join(dataHome, 'icons', 'hicolor', '256x256', 'apps', 'streamsnap.png');
  write(path.join(dataHome, 'applications', 'streamsnap.desktop'), `[Desktop Entry]
Type=Application
Name=StreamSnap
Comment=Stream movies and series via Torrentio and Real-Debrid
Exec="${wrapper}"
Path=${root}
Icon=${icon}
StartupWMClass=streamsnap
Terminal=false
Categories=AudioVideo;Video;Player;
`);
  for (const n of [16, 32, 48, 64, 128, 256, 512]) {
    try {
      const dest = path.join(dataHome, 'icons', 'hicolor', `${n}x${n}`, 'apps', 'streamsnap.png');
      const src = fs.readFileSync(path.join(root, 'public', 'icons', `${n}.png`));
      if (!fs.existsSync(dest) || !fs.readFileSync(dest).equals(src)) { fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, src); }
    } catch { /* ignore */ }
  }
  return path.join(dataHome, 'applications', 'streamsnap.desktop');
}

module.exports = { ensureDesktopEntry };
